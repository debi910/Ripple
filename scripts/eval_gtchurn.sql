WITH fe AS (SELECT PERSON_ID, MIN(EXPOSURE_DATE) FE FROM RIPPLE_GT.EXPOSURES GROUP BY 1)
SELECT CASE WHEN fe.PERSON_ID IS NULL THEN 'never' ELSE 'exposed' END G, COUNT(*) N,
 AVG(CASE WHEN c.PERSON_ID IS NOT NULL THEN 1.0 ELSE 0 END) CHURNED_EVER,
 AVG(CASE WHEN c.CHURN_DATE BETWEEN fe.FE AND fe.FE+42 THEN 1.0 ELSE 0 END) CHURN_42_AFTER,
 AVG(c.STOCKOUT_ATTRIBUTABLE_SHARE) ATTR
FROM (SELECT DISTINCT PERSON_ID FROM RIPPLE_GT.ACCOUNT_OWNERS) p LEFT JOIN fe ON fe.PERSON_ID=p.PERSON_ID LEFT JOIN RIPPLE_GT.CHURN c ON c.PERSON_ID=p.PERSON_ID GROUP BY 1;
