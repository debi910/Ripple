SELECT e.LINKED_BY, COUNT(*) N, SUM(CASE WHEN ga.PERSON_ID = g.PERSON_ID THEN 1 ELSE 0 END) CORRECT_PERSON
FROM RIPPLE.TICKETS_ENRICHED e JOIN RIPPLE_GT.TICKETS g ON g.TICKET_ID=e.TICKET_ID
LEFT JOIN (SELECT ap.PERSON_ID PRED, MIN(gw.PERSON_ID) PERSON_ID FROM RIPPLE.ACCOUNT_PERSON ap JOIN RIPPLE_GT.ACCOUNT_OWNERS gw ON gw.ACCOUNT_ID=ap.ACCOUNT_ID GROUP BY ap.PERSON_ID) ga ON ga.PRED=e.PERSON_ID
GROUP BY 1;
SELECT g.INTENT, COUNT(*) N, SUM(CASE WHEN e.INTENT=g.INTENT THEN 1 ELSE 0 END) CORRECT,
 SUM(CASE WHEN g.SKU_ID IS NOT NULL THEN 1 ELSE 0 END) HAS_SKU, SUM(CASE WHEN e.SKU_ID=g.SKU_ID THEN 1 ELSE 0 END) SKU_OK,
 SUM(CASE WHEN e.SKU_ID IS NOT NULL AND e.SKU_ID<>g.SKU_ID THEN 1 ELSE 0 END) SKU_WRONG
FROM RIPPLE.TICKETS_ENRICHED e JOIN RIPPLE_GT.TICKETS g ON g.TICKET_ID=e.TICKET_ID GROUP BY 1 ORDER BY 2 DESC;
