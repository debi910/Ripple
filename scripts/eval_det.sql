SELECT * FROM RIPPLE.DETECTOR_CALIBRATION;
SELECT * FROM RIPPLE.DETECTOR_PARAMS;
WITH m AS (
  SELECT e.VARIANT, g.EVENT_ID, g.DAYS, MIN(e.ALERT_DATE) ALERT, MIN(g.START_DATE) S, MIN(g.END_DATE) E
  FROM RIPPLE_GT.PHANTOM_EVENTS g JOIN RIPPLE.PHANTOM_EPISODES e ON e.STORE_ID=g.STORE_ID AND e.SKU_ID=g.SKU_ID
   AND e.ALERT_DATE BETWEEN g.START_DATE AND g.END_DATE + 1
  GROUP BY 1,2,3)
SELECT v.VARIANT,
  (SELECT COUNT(*) FROM RIPPLE.PHANTOM_EPISODES x WHERE x.VARIANT=v.VARIANT) EPISODES,
  (SELECT COUNT(*) FROM RIPPLE_GT.PHANTOM_EVENTS) GT_EVENTS,
  COUNT(m.EVENT_ID) DETECTED,
  AVG(DAYS_BETWEEN(m.ALERT, m.S)) AVG_DAYS_TO_ALERT,
  AVG(DAYS_BETWEEN(m.E, m.ALERT)) AVG_DAYS_EARLY
FROM (SELECT DISTINCT VARIANT FROM RIPPLE.PHANTOM_EPISODES) v LEFT JOIN m ON m.VARIANT=v.VARIANT GROUP BY v.VARIANT;
WITH fp AS (SELECT e.* FROM RIPPLE.PHANTOM_EPISODES e WHERE NOT EXISTS (SELECT 1 FROM RIPPLE_GT.PHANTOM_EVENTS g WHERE e.STORE_ID=g.STORE_ID AND e.SKU_ID=g.SKU_ID AND e.ALERT_DATE BETWEEN g.START_DATE AND g.END_DATE + 1))
SELECT VARIANT, COUNT(*) FP FROM fp GROUP BY 1;
SELECT CASE WHEN g.DAYS<=2 THEN '1-2' WHEN g.DAYS<=5 THEN '3-5' ELSE '6+' END LEN, COUNT(*) N FROM RIPPLE_GT.PHANTOM_EVENTS g GROUP BY 1;
