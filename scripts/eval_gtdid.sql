SELECT p.TREATED, CASE p.SEVERITY WHEN 2 THEN 'missing' WHEN 1 THEN 'sub' ELSE 'none' END K, COUNT(*) N,
 AVG(CASE WHEN c.CHURN_DATE BETWEEN p.WK AND p.WK+42 THEN 1.0 ELSE 0 END) GT_CHURN_6W,
 AVG(p.LOST*1.0) LOST
FROM RIPPLE.CAUSAL_PANEL p
JOIN (SELECT ap.PERSON_ID, MIN(g.PERSON_ID) GP FROM RIPPLE.ACCOUNT_PERSON ap JOIN RIPPLE_GT.ACCOUNT_OWNERS g ON g.ACCOUNT_ID=ap.ACCOUNT_ID GROUP BY 1) m ON m.PERSON_ID=p.PERSON_ID
LEFT JOIN RIPPLE_GT.CHURN c ON c.PERSON_ID=m.GP
GROUP BY 1,2;
