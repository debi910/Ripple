WITH pred AS (SELECT a.ACCOUNT_ID A, b.ACCOUNT_ID B FROM RIPPLE.ACCOUNT_PERSON a JOIN RIPPLE.ACCOUNT_PERSON b ON a.PERSON_ID=b.PERSON_ID AND a.ACCOUNT_ID<b.ACCOUNT_ID),
truth AS (SELECT a.ACCOUNT_ID A, b.ACCOUNT_ID B FROM RIPPLE_GT.ACCOUNT_OWNERS a JOIN RIPPLE_GT.ACCOUNT_OWNERS b ON a.PERSON_ID=b.PERSON_ID AND a.ACCOUNT_ID<b.ACCOUNT_ID)
SELECT (SELECT COUNT(*) FROM pred) PRED_PAIRS, (SELECT COUNT(*) FROM truth) TRUE_PAIRS,
 (SELECT COUNT(*) FROM pred p JOIN truth t ON p.A=t.A AND p.B=t.B) TP,
 (SELECT COUNT(DISTINCT PERSON_ID) FROM RIPPLE.ACCOUNT_PERSON) PRED_PERSONS,
 (SELECT COUNT(DISTINCT PERSON_ID) FROM RIPPLE_GT.ACCOUNT_OWNERS) TRUE_PERSONS,
 (SELECT COUNT(*) FROM RIPPLE_RAW.ACCOUNTS) ACCOUNTS;
