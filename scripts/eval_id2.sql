SELECT e.EMAIL_EQ, e.PHONE_EQ, e.PHONE_NAMES>1 AS SHARED, e.PIN_EQ, e.NAME_AGREE, COUNT(*) N,
  SUM(CASE WHEN ga.PERSON_ID=gb.PERSON_ID THEN 1 ELSE 0 END) TRUE_N
FROM RIPPLE.ID_PAIRS e JOIN RIPPLE_GT.ACCOUNT_OWNERS ga ON ga.ACCOUNT_ID=e.A JOIN RIPPLE_GT.ACCOUNT_OWNERS gb ON gb.ACCOUNT_ID=e.B
GROUP BY 1,2,3,4,5 ORDER BY N DESC LIMIT 30;
SELECT SIZE, COUNT(*) FROM (SELECT PERSON_ID, COUNT(*) SIZE FROM RIPPLE.ACCOUNT_PERSON GROUP BY 1) GROUP BY 1 ORDER BY 1 DESC LIMIT 8;
