-- The morning recount list: which shelves each store should count first.
-- Ranked by expected money saved, not by probability alone. A likely phantom
-- on a slow, cheap SKU matters less than a moderately likely one on a fast
-- mover whose shoppers churn. Uses the latest day in the data as "today".

CREATE OR REPLACE TABLE RIPPLE.COST_PER_EXPOSURE AS
SELECT s.CATEGORY,
       SUM(l.INR) / NULLIF(COUNT(DISTINCT x.ORDER_ID || '/' || x.LINE_NO), 0) AS INR_PER_SHORT_LINE
FROM RIPPLE.EPISODE_EXPOSURES x
JOIN RIPPLE_RAW.SKUS s ON s.SKU_ID = x.SKU_ID
JOIN RIPPLE.LEDGER l ON l.EPISODE_ID = x.EPISODE_ID AND l.PERSON_ID = x.PERSON_ID
GROUP BY s.CATEGORY;

CREATE OR REPLACE TABLE RIPPLE.COUNT_CADENCE AS
SELECT STORE_ID, SKU_ID, MAX(COUNT_DATE) AS LAST_COUNT,
       COALESCE(MEDIAN(GAP), 35) AS TYPICAL_GAP
FROM (SELECT STORE_ID, SKU_ID, COUNT_DATE,
             DAYS_BETWEEN(COUNT_DATE, LAG(COUNT_DATE) OVER (PARTITION BY STORE_ID, SKU_ID ORDER BY COUNT_DATE)) AS GAP
      FROM RIPPLE_RAW.CYCLE_COUNTS)
GROUP BY STORE_ID, SKU_ID;

CREATE OR REPLACE TABLE RIPPLE.RECOUNT_LIST AS
WITH today AS (SELECT MAX(D) AS AS_OF FROM RIPPLE.PHANTOM_SCORES),
open_now AS (
    SELECT s.STORE_ID, s.SKU_ID, s.P_PHANTOM, s.LAMBDA_HAT, s.LLR_SALES, s.LLR_OMS, s.LLR_PICK, s.LLR_TICKETS, t.AS_OF
    FROM RIPPLE.PHANTOM_SCORES s JOIN today t ON s.D = t.AS_OF
    WHERE s.VARIANT = 'all' AND s.P_PHANTOM >= 0.3
),
evidence AS (
    -- Why we think so, in the customers' own words.
    SELECT o.STORE_ID, o.SKU_ID,
           LISTAGG(SUBSTR(te.BODY, 1, 140), ' | ') WITHIN GROUP (ORDER BY te.CREATED_AT DESC) AS TICKET_QUOTES,
           COUNT(*) AS TICKETS_14D
    FROM open_now o JOIN RIPPLE.TICKETS_ENRICHED te
      ON te.STORE_ID = o.STORE_ID AND te.SKU_ID = o.SKU_ID AND te.TICKET_DATE > o.AS_OF - 14
    GROUP BY o.STORE_ID, o.SKU_ID
),
silence AS (
    SELECT o.STORE_ID, o.SKU_ID,
           SUM(CASE WHEN d.UNITS = 0 THEN 1 ELSE 0 END) AS ZERO_SALE_DAYS_7D,
           SUM(d.SHORT_LINES) AS SHORT_LINES_7D, MAX(d.BOOK_EOD) AS BOOK_QTY
    FROM open_now o JOIN RIPPLE.SKU_DAY d
      ON d.STORE_ID = o.STORE_ID AND d.SKU_ID = o.SKU_ID AND d.D > o.AS_OF - 7
    GROUP BY o.STORE_ID, o.SKU_ID
)
SELECT o.AS_OF, o.STORE_ID, st.NAME AS STORE_NAME, o.SKU_ID, s.NAME AS SKU_NAME, s.CATEGORY,
       o.P_PHANTOM, o.LAMBDA_HAT AS DAILY_DEMAND, si.BOOK_QTY, si.ZERO_SALE_DAYS_7D, si.SHORT_LINES_7D,
       GREATEST(c.LAST_COUNT + c.TYPICAL_GAP - o.AS_OF, 1) AS DAYS_TO_NEXT_COUNT,
       -- Expected loss avoided by counting today instead of waiting for the scheduled count.
       o.P_PHANTOM * o.LAMBDA_HAT * cpe.INR_PER_SHORT_LINE * GREATEST(c.LAST_COUNT + c.TYPICAL_GAP - o.AS_OF, 1)
         AS EXPECTED_SAVING_INR,
       o.LLR_SALES, o.LLR_OMS, o.LLR_PICK, o.LLR_TICKETS,
       COALESCE(ev.TICKETS_14D, 0) AS TICKETS_14D, ev.TICKET_QUOTES
FROM open_now o
JOIN RIPPLE_RAW.SKUS s ON s.SKU_ID = o.SKU_ID
JOIN RIPPLE_RAW.STORES st ON st.STORE_ID = o.STORE_ID
LEFT JOIN RIPPLE.COUNT_CADENCE c ON c.STORE_ID = o.STORE_ID AND c.SKU_ID = o.SKU_ID
LEFT JOIN RIPPLE.COST_PER_EXPOSURE cpe ON cpe.CATEGORY = s.CATEGORY
LEFT JOIN evidence ev ON ev.STORE_ID = o.STORE_ID AND ev.SKU_ID = o.SKU_ID
LEFT JOIN silence si ON si.STORE_ID = o.STORE_ID AND si.SKU_ID = o.SKU_ID;
