-- Ripple: source systems as they arrive, one schema per silo-free landing zone.
-- RIPPLE_RAW holds the five source systems untouched. RIPPLE_GT holds the
-- simulator's answer key and is read only by the evaluation step (90_eval.sql).

CREATE SCHEMA IF NOT EXISTS RIPPLE_RAW;
CREATE SCHEMA IF NOT EXISTS RIPPLE_GT;
CREATE SCHEMA IF NOT EXISTS RIPPLE;

-- Merchandising / inventory system
CREATE OR REPLACE TABLE RIPPLE_RAW.STORES (
    STORE_ID        DECIMAL(9,0),
    NAME            VARCHAR(100),
    CITY            VARCHAR(50),
    AREA            VARCHAR(50),
    PINCODE_PREFIX  VARCHAR(6),
    OPENED          DATE
);
CREATE OR REPLACE TABLE RIPPLE_RAW.SKUS (
    SKU_ID           DECIMAL(9,0),
    NAME             VARCHAR(200),
    BRAND            VARCHAR(50),
    CATEGORY         VARCHAR(50),
    SUBSTITUTE_GROUP VARCHAR(50),
    PACK_SIZE        VARCHAR(20),
    PRICE            DECIMAL(10,2),
    UNIT_COST        DECIMAL(10,2),
    PERISHABLE       BOOLEAN
);
CREATE OR REPLACE TABLE RIPPLE_RAW.INVENTORY_BOOK (
    SNAPSHOT_DATE DATE,
    STORE_ID      DECIMAL(9,0),
    SKU_ID        DECIMAL(9,0),
    BOOK_QTY      DECIMAL(9,0)
);
CREATE OR REPLACE TABLE RIPPLE_RAW.CYCLE_COUNTS (
    STORE_ID    DECIMAL(9,0),
    SKU_ID      DECIMAL(9,0),
    COUNT_DATE  DATE,
    BOOK_QTY    DECIMAL(9,0),
    COUNTED_QTY DECIMAL(9,0)
);

-- Point of sale
CREATE OR REPLACE TABLE RIPPLE_RAW.SALES_DAILY (
    SALE_DATE DATE,
    STORE_ID  DECIMAL(9,0),
    SKU_ID    DECIMAL(9,0),
    UNITS     DECIMAL(9,0)
);

-- Order management and picking
CREATE OR REPLACE TABLE RIPPLE_RAW.ACCOUNTS (
    ACCOUNT_ID   DECIMAL(12,0),
    CHANNEL      VARCHAR(20),
    DISPLAY_NAME VARCHAR(100),
    EMAIL        VARCHAR(200),
    PHONE        VARCHAR(30),
    PINCODE      VARCHAR(10),
    CREATED_ON   DATE
);
CREATE OR REPLACE TABLE RIPPLE_RAW.ORDERS (
    ORDER_ID   DECIMAL(12,0),
    ACCOUNT_ID DECIMAL(12,0),
    STORE_ID   DECIMAL(9,0),
    ORDERED_AT TIMESTAMP
);
CREATE OR REPLACE TABLE RIPPLE_RAW.ORDER_LINES (
    ORDER_ID         DECIMAL(12,0),
    LINE_NO          DECIMAL(4,0),
    SKU_ID           DECIMAL(9,0),
    QTY              DECIMAL(6,0),
    FULFILLED_SKU_ID DECIMAL(9,0),
    LINE_STATUS      VARCHAR(20),
    UNIT_PRICE       DECIMAL(10,2)
);
CREATE OR REPLACE TABLE RIPPLE_RAW.PICK_EXCEPTIONS (
    STORE_ID  DECIMAL(9,0),
    SKU_ID    DECIMAL(9,0),
    PICK_DATE DATE,
    ORDER_ID  DECIMAL(12,0),
    REASON    VARCHAR(30)
);
CREATE OR REPLACE TABLE RIPPLE_RAW.NOTIFY_REQUESTS (
    ACCOUNT_ID   DECIMAL(12,0),
    STORE_ID     DECIMAL(9,0),
    SKU_ID       DECIMAL(9,0),
    REQUESTED_AT TIMESTAMP
);

-- Returns platform
CREATE OR REPLACE TABLE RIPPLE_RAW.PRODUCT_RETURNS (
    RETURN_ID     DECIMAL(12,0),
    ORDER_ID      DECIMAL(12,0),
    LINE_NO       DECIMAL(4,0),
    RETURN_DATE   DATE,
    REASON_CODE   VARCHAR(30),
    REFUND_AMOUNT DECIMAL(10,2)
);

-- Helpdesk
CREATE OR REPLACE TABLE RIPPLE_RAW.TICKETS (
    TICKET_ID  DECIMAL(12,0),
    CREATED_AT TIMESTAMP,
    CHANNEL    VARCHAR(20),
    FROM_NAME  VARCHAR(100),
    FROM_EMAIL VARCHAR(200),
    FROM_PHONE VARCHAR(30),
    ORDER_REF  VARCHAR(20),
    BODY       VARCHAR(2000)
);

-- Simulator answer key (evaluation only)
CREATE OR REPLACE TABLE RIPPLE_GT.PHANTOM_EVENTS (
    EVENT_ID   DECIMAL(9,0),
    STORE_ID   DECIMAL(9,0),
    SKU_ID     DECIMAL(9,0),
    START_DATE DATE,
    END_DATE   DATE,
    DAYS       DECIMAL(6,0)
);
CREATE OR REPLACE TABLE RIPPLE_GT.ACCOUNT_OWNERS (
    ACCOUNT_ID DECIMAL(12,0),
    PERSON_ID  DECIMAL(12,0)
);
CREATE OR REPLACE TABLE RIPPLE_GT.TICKETS (
    TICKET_ID DECIMAL(12,0),
    PERSON_ID DECIMAL(12,0),
    INTENT    VARCHAR(40),
    SKU_ID    DECIMAL(9,0)
);
CREATE OR REPLACE TABLE RIPPLE_GT.EXPOSURES (
    PERSON_ID      DECIMAL(12,0),
    EXPOSURE_DATE  DATE,
    STORE_ID       DECIMAL(9,0),
    SKU_ID         DECIMAL(9,0),
    ORDER_ID       DECIMAL(12,0),
    KIND           VARCHAR(20),
    DURING_PHANTOM BOOLEAN
);
CREATE OR REPLACE TABLE RIPPLE_GT.CHURN (
    PERSON_ID                   DECIMAL(12,0),
    CHURN_DATE                  DATE,
    STOCKOUT_ATTRIBUTABLE_SHARE DECIMAL(6,4)
);
